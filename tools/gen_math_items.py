"""Generate bug-discriminating slate arithmetic items into a content pack (guide §6.3.1).

Usage:  services/api/.venv/Scripts/python tools/gen_math_items.py [--pack content/packs/hi-IN] [--n 10]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "services" / "api"))

from app.diagnosis.itemgen import SPACES, generate  # noqa: E402

GRADE = {"M6": 2, "M7": 2, "M8": 2, "M9": 2, "M10": 3}
PRIMARY_SKILLS = {"M6": ["M6"], "M7": ["M7", "M5"], "M8": ["M8"], "M9": ["M9", "M5"], "M10": ["M10"]}

# Grade-1 single-digit facts (NIPUN Grade 1: add/subtract within 9). Few bugs apply; they still give
# skill evidence and operation-swap detection.
GRADE1 = [(3, 4, "+"), (5, 2, "+"), (6, 3, "-"), (8, 5, "-"), (4, 4, "+"), (9, 6, "-")]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--pack", default=str(ROOT / "content" / "packs" / "hi-IN"))
    ap.add_argument("--n", type=int, default=10)
    args = ap.parse_args()
    out = []
    for a, b, op in GRADE1:
        skill = "M6" if op == "+" else "M8"
        out.append({"id": f"m.slate.g1.{a}{op}{b}".replace("+", "p").replace("-", "m"), "type": "slate", "grade": 1,
                    "skills": [skill], "a": a, "b": b, "op": op, "probes": [], "signature": {}})
    for skill in SPACES:
        for it in generate(skill, n=args.n):
            out.append({
                "id": f"m.slate.{skill}.{it.a}{'p' if it.op == '+' else 'm'}{it.b}",
                "type": "slate", "grade": GRADE[skill], "skills": PRIMARY_SKILLS[skill],
                "a": it.a, "b": it.b, "op": it.op,
                "probes": sorted(it.signature), "signature": it.signature, "discrimination": it.discrimination,
            })
    path = Path(args.pack) / "items" / "math_slate.yaml"
    header = "# GENERATED by tools/gen_math_items.py — do not edit by hand; re-run the tool instead.\n"
    path.write_text(header + yaml.safe_dump(out, allow_unicode=True, sort_keys=False, width=120), encoding="utf-8")
    print(f"wrote {len(out)} items -> {path}")


if __name__ == "__main__":
    main()
